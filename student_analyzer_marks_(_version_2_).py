import matplotlib.pyplot as plt

PASS_MARK = 45


def ordinal(n):
    if 10 <= n % 100 <= 20:
        suffix = "th"
    else:
        suffix = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def get_marks():
    subjects = {}

    while True:
        try:
            n = int(input("Specify the total number of subjects: "))
            print("-" * 40)
            if n > 0:
                break
            print("Enter at least 1 subject")
        except ValueError:
            print("Please enter a whole number")
    print()
    for i in range(1, n + 1):
        while True:
            name = input(f"Enter name of {ordinal(i)} subject: ").strip().title()
            print()
            if name == "":
                print("Subject name cannot be empty")
            elif name in subjects:
                print("That subject is already added")
            else:
                break

        while True:
            try:
                m = float(input(f"Enter marks of {ordinal(i)} subject ({name}) (0-100): "))
            except ValueError:
                print("Invalid! Please enter a number")
                continue
            if 0 <= m <= 100:
                subjects[name] = m
                break
            print("Invalid! Marks must be between 0 and 100")
        print()
        print()
    return subjects


def show_chart(subjects):
    names = list(subjects.keys())
    marks = list(subjects.values())
    colors = ["seagreen" if m >= PASS_MARK else "indianred" for m in marks]

    plt.figure(figsize=(8, 5))
    bars = plt.bar(names, marks, color=colors)
    plt.axhline(PASS_MARK, color="gray", linestyle="--", label=f"Pass mark ({PASS_MARK})")

    for bar, m in zip(bars, marks):
        plt.text(bar.get_x() + bar.get_width() / 2, m + 1, f"{m:g}",
                 ha="center", fontsize=9)

    plt.ylim(0, 110)
    plt.xlabel("Subjects")
    plt.ylabel("Marks")
    plt.title("Student Performance Report")
    plt.legend()
    plt.tight_layout()
    plt.show()


def analyze_marks(subjects):
    total = 0
    highest_name = lowest_name = None
    highest = lowest = None

    print("." * 30)
    print("Subject-wise Status".center(30))
    print("." * 30)
    print(f"{'Name':<15} {'Score':>6}   {'Status'}")
    print("-" * 30)

    for name, m in subjects.items():
        total += m
        if highest is None or m > highest:
            highest, highest_name = m, name
        if lowest is None or m < lowest:
            lowest, lowest_name = m, name

        status = "Pass" if m >= PASS_MARK else "Fail"
        print(f"{name:<15} {m:>6.1f}   {status}")

    avg = total / len(subjects)
    percentage = total / (len(subjects) * 100) * 100

    if percentage >= 90:
        grade = "A"
    elif percentage >= 80:
        grade = "B"
    elif percentage >= 70:
        grade = "C"
    elif percentage >= 60:
        grade = "D"
    elif percentage >= 45:
        grade = "E"
    else:
        grade = "Fail"

    print()
    print("." * 15)
    print("Result".center(15))
    print("." * 15)
    print("Total:", total)
    print(f"Highest: {highest} ({highest_name})")
    print(f"Lowest: {lowest} ({lowest_name})")
    print(f"Percentage: {percentage:.2f}%")
    print("Grade:", grade)
    print()
subjects = get_marks()
analyze_marks(subjects)
show_chart(subjects)

